const STORAGE_KEY = "restaurant-color-theme"
const DEFAULT_PALETTE = "terracota"

/** Get the stored palette name, or default */
export function getStoredPalette(): string {
    if (typeof window === "undefined") return DEFAULT_PALETTE
    return localStorage.getItem(STORAGE_KEY) || DEFAULT_PALETTE
}

/** Save the palette selection */
export function savePalette(name: string) {
    if (typeof window === "undefined") return
    localStorage.setItem(STORAGE_KEY, name)
}

/** Apply a palette's CSS variables to :root based on current dark/light mode */
export function applyPalette(paletteName: string) {
    const palette = COLOR_PALETTES.find(p => p.name === paletteName)
    if (!palette) return

    const root = document.documentElement
    const isDark = root.classList.contains("dark")
    const vars = isDark ? palette.dark : palette.light

    Object.entries(vars).forEach(([key, value]) => {
        root.style.setProperty(key, value)
    })
}

/** Remove all inline palette styles so CSS classes take effect */
export function clearPaletteStyles() {
    const root = document.documentElement
    const samplePalette = COLOR_PALETTES[0]
    if (!samplePalette) return

    Object.keys(samplePalette.light).forEach(key => {
        root.style.removeProperty(key)
    })
}
